/**
 * The frozen public API: every export
 * of every package entry, and every declaration of the package they reference,
 * as their declaration text from dist/types. `pnpm api` writes
 * docs/api/report.md; `pnpm api --check` fails when the declarations no longer
 * match it, so a change to the surface is always a reviewed change of the report.
 * Needs `pnpm build` first.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'
import ts from 'typescript'

const root = resolve(import.meta.dirname, '..')
const types = join(root, 'dist/types')
const report = join(root, 'docs/api/report.md')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const entries = Object.entries(pkg.exports)
  .filter(([, e]) => typeof e === 'object' && e.types)
  .map(([name, e]) => [name === '.' ? '@lamka02sk/proza' : `@lamka02sk/proza/${name.slice(2)}`, join(root, e.types)])

const program = ts.createProgram(entries.map(([, f]) => f), { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler, skipLibCheck: true, noEmit: true })
const checker = program.getTypeChecker()
const printer = ts.createPrinter({ removeComments: true, newLine: ts.NewLineKind.LineFeed })
const ours = (decl) => decl.getSourceFile().fileName.startsWith(types)
const where = (decl) => relative(types, decl.getSourceFile().fileName)
const text = (decl) => {
  // A variable's statement holds its type; the declaration alone prints without `declare const`.
  const node = ts.isVariableDeclaration(decl) ? decl.parent.parent : decl
  return printer.printNode(ts.EmitHint.Unspecified, node, node.getSourceFile()).replace(/^export /, '').replace(/^declare /, '')
}
const resolveAlias = (s) => (s.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(s) : s)

const printed = new Set()
const queue = []
const declsOf = (sym) => (resolveAlias(sym).declarations ?? []).filter(ours)
/** Types of the package a declaration names: they are part of the surface too. */
const references = (node) => {
  const visit = (n) => {
    if ((ts.isTypeReferenceNode(n) || ts.isExpressionWithTypeArguments(n) || ts.isTypeQueryNode(n)) && !printed.has(n)) {
      const name = ts.isTypeReferenceNode(n) ? n.typeName : ts.isTypeQueryNode(n) ? n.exprName : n.expression
      const sym = checker.getSymbolAtLocation(ts.isQualifiedName(name) ? name.right : name)
      if (sym) for (const d of declsOf(sym)) if (!printed.has(d)) { printed.add(d); queue.push(d) }
    }
    ts.forEachChild(n, visit)
  }
  visit(node)
}

let out = '# Public API\n\nGenerated by `pnpm api` from the published declarations (`pnpm build`). Do not edit: change the source, then run `pnpm api` and review the difference.\n'
for (const [name, file] of entries) {
  const sf = program.getSourceFile(file)
  const mod = checker.getSymbolAtLocation(sf)
  const exports = checker.getExportsOfModule(mod).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
  out += `\n## \`${name}\`\n\n\`\`\`ts\n`
  for (const e of exports) {
    const decls = declsOf(e)
    if (decls.length === 0) { out += `// ${e.name}: from a dependency\n`; continue }
    for (const d of decls) {
      printed.add(d)
      references(d)
      const own = resolveAlias(e).name
      out += `${own === e.name ? '' : `// exported as ${e.name}\n`}${text(d)}\n`
    }
  }
  out += '```\n'
}
// Declarations the exports name but do not export themselves, with where they live.
out += '\n## Referenced declarations\n\nTypes the exports use that are not exported by name. They are part of the surface: their shape is frozen with it.\n\n```ts\n'
const seenText = new Set()
while (queue.length) {
  const d = queue.shift()
  references(d)
  const t = text(d)
  if (seenText.has(t)) continue
  seenText.add(t)
  out += `// ${where(d)}\n${t}\n`
}
out += '```\n'

if (process.argv.includes('--check')) {
  let old = ''
  try { old = readFileSync(report, 'utf8') } catch { /* no report yet */ }
  if (old !== out) {
    console.error('✗ The public API differs from docs/api/report.md. Run `pnpm build && pnpm api`, review the difference, and commit it.')
    process.exit(1)
  }
  console.log('✓ public API matches docs/api/report.md')
} else {
  writeFileSync(report, out)
  console.log(`docs/api/report.md: ${out.split('\n').length} lines`)
}
