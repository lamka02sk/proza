/** A message value as text. */
const q = (v: string | number | undefined): string => String(v ?? '')

/** Czech plural: 1 část, 2 až 4 části, 5 a více částí. */
function plural(n: number, one: string, few: string, many: string): string {
  return n === 1 ? one : n >= 2 && n <= 4 ? few : many
}

const parts = (n: number, one: string, few: string, many: string): string =>
  n === 1 ? `Část ${one}` : `${n} ${plural(n, 'část', 'části', 'částí')} ${plural(n, one, few, many)}`

