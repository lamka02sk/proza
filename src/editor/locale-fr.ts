/** A message value as text. */
const q = (v: string | number | undefined): string => String(v ?? '')

/** French plural: 0 and 1 take the singular, 2 and more the plural. */
function plural(n: number, one: string, many: string): string {
  return n < 2 ? one : many
}

const parts = (n: number, one: string, many: string): string =>
  n === 1 ? `Partie ${one}` : `${n} ${plural(n, 'partie', 'parties')} ${plural(n, one, many)}`

const problems = (n: number): string => (n === 1 ? 'un problème' : `${String(n)} ${plural(n, 'problème', 'problèmes')}`)

